#!/usr/bin/env python3
"""Generate ZeePlay edition copy without modifying the standard edition or storage/URL names."""
import argparse
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
NAME = "ZeePlay"
STRING = re.compile(r"(<string(?=\s)[^>]*>)(.*?)(</string>)", re.S)
PROTECTED = re.compile(r'https?://[^\s<"\\]+|(?:Downloads?|下载|下載)/DiPlay|docs/[A-Za-z0-9_./-]+')

def branded(body):
    protected = []
    def save(match):
        protected.append(match[0])
        return f"__BRAND_PATH_{len(protected) - 1}__"
    value = PROTECTED.sub(save, body).replace("DiPlay", NAME)
    for i, original in enumerate(protected):
        value = value.replace(f"__BRAND_PATH_{i}__", original)
    return value

def outputs():
    result = {}
    for module in ("common", "mobile"):
        grouped = {}
        for source in sorted((ROOT / module / "src/main/res").glob("values*/*.xml")):
            for match in STRING.finditer(source.read_text()):
                body = branded(match[2])
                if body == match[2]:
                    continue
                element = ET.fromstring(match[0])
                name = element.attrib["name"]
                grouped.setdefault(source.parent.name, {})[name] = match[1] + body + match[3]
        for qualifier, strings in grouped.items():
            path = ROOT / module / "src/zeekr/res" / qualifier / "branding.xml"
            result[path] = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<!-- Generated by scripts/sync_zeekr_branding.py; edit the source locale copy. -->\n'
                '<resources>\n' + ''.join("    " + value + "\n" for _, value in sorted(strings.items())) + '</resources>\n')
    return result

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = outputs()
    stale = []
    for path, text in expected.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    existing = set((ROOT / "common/src/zeekr/res").glob("values*/branding.xml")) | set((ROOT / "mobile/src/zeekr/res").glob("values*/branding.xml"))
    for path in existing - expected.keys():
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.unlink()
    if stale:
        raise SystemExit("Run python3 scripts/sync_zeekr_branding.py:\n" + "\n".join(stale))
    print(f"ZeePlay locale overlays {'verified' if args.check else 'generated'}: {len(expected)} files")
